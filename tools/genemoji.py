#!/usr/bin/env python3
"""Generates src/emoji_data.inc from gemoji's emoji.json (github/gemoji
v4.1.0, MIT): every emoji with its shortcodes, in the picker's order."""
import json
import os

here = os.path.dirname(os.path.abspath(__file__))
data = json.load(open(os.path.join(here, "gemoji.json"), encoding="utf-8"))
cats = ["Smileys & Emotion", "People & Body", "Animals & Nature", "Food & Drink",
        "Travel & Places", "Activities", "Objects", "Symbols", "Flags"]


def c(s):
    return '"' + "".join("\\x%02x" % b for b in s.encode("utf-8")) + '"'


out = ["// Generated by tools/genemoji.py from gemoji's emoji.json. Do not edit.",
       "// { emoji, space-separated shortcodes, category }"]
for e in data:
    out.append("{%s, \"%s\", %d}," % (c(e["emoji"]), " ".join(e["aliases"]), cats.index(e["category"])))
open(os.path.join(here, "..", "src", "emoji_data.inc"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
